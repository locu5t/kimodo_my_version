def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)

def unregister():
    if bpy.context.scene and hasattr(bpy.types.Scene,'kimodo_studio') and bpy.context.scene.kimodo_studio.edit_object:
        cleanup_editor(bpy.context)
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
