class KMD_OT_Example(bpy.types.Operator,ImportHelper):
    bl_idname='kimodo.load_example'; bl_label='Load example (select meta.json)'
    filename_ext='.json'; filter_glob:StringProperty(default='meta.json;*.json',options={'HIDDEN'})
    def execute(self,context):
        try:
            path=Path(self.filepath); data=load_authoring_json(path)
            prompts=parse_prompts(data); s=context.scene.kimodo_studio
            if s.editing_index>=0:
                raise ValueError('Apply or cancel the pose edit first')
            frame_prompts(prompts,rig.scene_fps(context.scene))
            constraint_path=path.parent/'constraints.json'
            records=native_to_records(load_authoring_json(constraint_path),s.constraint_import_fps,
                rig.scene_fps(context.scene),s.start_frame) if constraint_path.exists() else []
            ui._SUSPEND_UPDATES=True
            try:
                s.prompts.clear(); s.constraints.clear()
                for prompt in prompts:
                    item=s.prompts.add(); item.text=prompt.text; item.duration=float(prompt.duration)
                for r in records:
                    put_record(s,r)
                s.preview_append=False
            finally:
                ui._SUSPEND_UPDATES=False
            ui.update_markers(context.scene)
            motion=path.parent/'motion.npz'
            if motion.is_file():
                return bpy.ops.kimodo.run_job('INVOKE_DEFAULT',operation='import',source_file=str(motion))
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


class KMD_OT_Take(bpy.types.Operator):
    bl_idname='kimodo.take_action'; bl_label='Take action'
    bl_options={'REGISTER','UNDO'}
    action:EnumProperty(items=[(x,x.title(),'') for x in ('SELECT','SOURCE','SOLO','SHOW_ALL')])
    def execute(self,context):
        s=context.scene.kimodo_studio
        if not s.takes:
            return {'CANCELLED'}
        take=s.takes[max(0,min(s.take_index,len(s.takes)-1))]; obj=take.rig
        if obj is None or obj.name not in context.scene.objects:
            self.report({'ERROR'},'The take rig was deleted or moved to another scene'); return {'CANCELLED'}
        if self.action in {'SOLO','SHOW_ALL'}:
            for row in s.takes:
                if row.rig and row.rig.name in context.view_layer.objects:
                    row.rig.hide_set(self.action=='SOLO' and row.rig!=obj)
        else:
            select_only(context,obj)
            if self.action=='SOURCE':
                s.rig_source=obj
                s.source_start=math.ceil(obj.get('kimodo_frame_start',context.scene.frame_start))
                s.source_end=math.floor(obj.get('kimodo_frame_end',context.scene.frame_end))
                s.preview_append=True
        return {'FINISHED'}


class KMD_OT_Visualize(bpy.types.Operator):
    bl_idname='kimodo.visualize'; bl_label='Update visualization'
    bl_options={'REGISTER','UNDO'}
    action:EnumProperty(items=[(x,x.title(),'') for x in ('APPLY','FRAME','PATH')])
    def execute(self,context):
        try:
            s=context.scene.kimodo_studio; obj=source_object(context)
            if self.action=='PATH':
                with tempfile.TemporaryDirectory() as tmp:
                    clip=rig.snapshot(obj,context.scene,s.source_start,s.source_end,Path(tmp)/'path.npz')
                data=bpy.data.curves.new('Kimodo Root Trajectory','CURVE'); data.dimensions='3D'
                spline=data.splines.new('POLY'); spline.points.add(len(clip.root)-1)
                for p,point in zip(spline.points,clip.root @ C.T):
                    p.co=(*point,1.)
                data.bevel_depth=.008
                path=bpy.data.objects.new('Kimodo Root Trajectory',data); context.scene.collection.objects.link(path)
            else:
                obj.data.display_type=s.display_type; obj.data.show_names=s.show_names; obj.show_in_front=s.in_front
                for area in context.screen.areas:
                    if area.type=='VIEW_3D':
                        space=area.spaces.active; space.overlay.show_floor=s.show_floor; space.shading.type=s.viewport_shading
                        if self.action=='FRAME':
                            select_only(context,obj)
                            region=next((r for r in area.regions if r.type=='WINDOW'),None)
                            if region:
                                with context.temp_override(area=area,region=region):
                                    bpy.ops.view3d.view_selected(use_all_regions=False)
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


class KMD_OT_Workspace(bpy.types.Operator):
    bl_idname='kimodo.setup_workspace'; bl_label='Create Kimodo workspace'
    bl_description='Duplicate this workspace and prepare a native viewport/Dope Sheet layout'
    def execute(self,context):
        if ui._ACTIVE:
            self.report({'ERROR'},'Finish the current job first'); return {'CANCELLED'}
        bpy.ops.workspace.duplicate()
        context.workspace.name='Kimodo Motion Studio'
        areas=list(context.screen.areas)
        timeline=next((a for a in areas if a.type=='DOPESHEET_EDITOR'),None)
        if timeline is None:
            viewport=next((a for a in areas if a.type=='VIEW_3D'),None)
            if viewport:
                with context.temp_override(area=viewport):
                    bpy.ops.screen.area_split(direction='HORIZONTAL',factor=.28)
                views=[a for a in context.screen.areas if a.type=='VIEW_3D']
                timeline=min(views,key=lambda a:a.y)
        if timeline:
            timeline.type='DOPESHEET_EDITOR'; timeline.ui_type='DOPESHEET'
            timeline.spaces.active.show_region_ui=True
        for area in context.screen.areas:
            if area.type=='VIEW_3D':
                area.spaces.active.show_region_ui=True
        context.scene.kimodo_studio.overlay=True
        self.report({'INFO'},'Open the Kimodo sidebar; enlarge the Dope Sheet to reveal all tracks')
        return {'FINISHED'}


