def migrate_legacy():
    """Migrate earlier scaffold scene ID properties, without changing backend preferences."""
    for scene in bpy.data.scenes:
        old=scene.get('kimodo_motion')
        if old and not scene.kimodo_studio.prompts:
            try:
                for row in old.get('prompts',[]):
                    p=scene.kimodo_studio.prompts.add(); p.text=row.get('text','Motion')
                    p.duration=row.get('duration',6.); p.enabled=row.get('enabled',True)
            except (TypeError,AttributeError):
                pass


