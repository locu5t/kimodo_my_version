def make_project(scene):
    s=scene.kimodo_studio
    settings={k:getattr(s,k) for k in PROJECT_SETTINGS}
    settings['model']=s.model if s.custom_model else model_name(s.dataset,s.skeleton_choice,s.version_choice)
    return normalize_project({'kind':'kimodo-studio-project','schema_version':2,'fps':rig.scene_fps(scene),
        'prompts':[{'text':p.text,'duration':p.duration,'enabled':p.enabled} for p in s.prompts],
        'constraints':constraint_records(s),'settings':settings})


def apply_project(scene,data):
    if scene.kimodo_studio.editing_index>=0:
        raise ValueError('Apply or cancel the constraint pose edit before loading a project')
    data=normalize_project(data)
    if abs(data['fps']-rig.scene_fps(scene))>.0001:
        raise ValueError(f"Project uses {data['fps']} FPS. Set the scene to that rate before importing")
    s=scene.kimodo_studio
    # Validate property bounds before mutating Blender state; do not silently clamp.
    for key,value in data['settings'].items():
        prop=s.bl_rna.properties[key]
        if isinstance(value,(int,float)) and not isinstance(value,bool):
            if not prop.hard_min<=value<=prop.hard_max:
                raise ValueError(f'Project setting {key} is outside the supported range')
    ui._SUSPEND_UPDATES=True
    try:
        s.prompts.clear(); s.constraints.clear()
        for row in data['prompts']:
            p=s.prompts.add(); p.text=row['text']; p.duration=float(row.get('duration',row.get('duration_seconds')))
            p.enabled=row.get('enabled',True)
        for r in data['constraints']:
            put_record(s,r)
        for key,value in data['settings'].items():
            setattr(s,key,value)
        if 'model' in data['settings']:
            s.custom_model=True
        s.index=0
    finally:
        ui._SUSPEND_UPDATES=False
    ui.update_markers(scene)


class KMD_OT_LoadProject(bpy.types.Operator,ImportHelper):
    bl_idname='kimodo.load_project'; bl_label='Load Studio project JSON'
