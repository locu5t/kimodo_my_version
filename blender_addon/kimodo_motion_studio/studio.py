def source_object(context):
    obj=context.scene.kimodo_studio.rig_source or context.object
    if obj is None or obj.type!='ARMATURE' or 'kimodo_skeleton_json' not in obj:
        raise ValueError('Choose a native Kimodo rig imported/generated by this add-on')
    if obj.name not in context.scene.objects:
        raise ValueError('Source rig belongs to another scene')
    return obj


def constraint_records(settings):
    records=[]
    for item in settings.constraints:
        payload=json.loads(item.payload)
        if item.target and item.kind=='root2d':
            p=C.T @ np.asarray(item.target.matrix_world.translation)
            payload['smooth_root_2d']=[p[[0,2]].tolist()]*len(payload['smooth_root_2d'])
        record={'name':item.name,'type':item.kind,'enabled':item.enabled,
                'start_frame':item.start_frame,'end_frame':item.end_frame,
                'payload':payload,'translation':list(item.translation)}
        meta=json.loads(item.skeleton)
        if meta:
            record['skeleton']=meta
        records.append(validate_record(record))
    return records


def put_record(settings, record):
    r=validate_record(record)
    item=settings.constraints.add()
    item.name=r.get('name',r['type']); item.kind=r['type']; item.enabled=r.get('enabled',True)
    item.start_frame=r['start_frame']; item.end_frame=r['end_frame']
    item.payload=json.dumps(r['payload']); item.skeleton=json.dumps(r.get('skeleton',{}))
    item.translation=r.get('translation',[0,0,0])
    settings.constraint_index=len(settings.constraints)-1
    return item


def sampled_record(context, kind, start, end):
    if end<start or end-start>1199:
        raise ValueError('Capture 1–1200 frames per interval')
    obj=source_object(context)
    with tempfile.TemporaryDirectory(prefix='kimodo-pose-') as tmp:
        clip=rig.snapshot(obj,context.scene,start,max(start+1,end),Path(tmp)/'pose.npz')
    count=end-start+1
    if kind=='root2d':
        payload={'smooth_root_2d':clip.root[:count,[0,2]].tolist()}
    else:
        payload={'local_rot_mats':clip.local[:count].tolist(),'root_positions':clip.root[:count].tolist()}
    return {'name':dict(TRACKS).get(kind,kind),'type':kind,'enabled':True,
            'start_frame':start,'end_frame':end,'payload':payload,
            'skeleton':json.loads(obj['kimodo_skeleton_json'])}


def select_only(context,obj):
    if context.mode!='OBJECT':
        bpy.ops.object.mode_set(mode='OBJECT')
    for selected in context.selected_objects:
        selected.select_set(False)
    obj.hide_set(False); obj.select_set(True); context.view_layer.objects.active=obj


def cleanup_editor(context):
    s=context.scene.kimodo_studio
    obj=s.edit_object
    if obj:
        if obj.mode!='OBJECT':
            context.view_layer.objects.active=obj; bpy.ops.object.mode_set(mode='OBJECT')
        arm=obj.data
        bpy.data.objects.remove(obj,do_unlink=True)
        if arm.users==0:
            bpy.data.armatures.remove(arm)
    s.edit_object=None; s.editing_index=-1
    if s.rig_source and s.rig_source.name in context.scene.objects:
        select_only(context,s.rig_source)


class KMD_OT_Capture(bpy.types.Operator):
    bl_idname='kimodo.capture_constraint'
    bl_label='Capture constraint'
    bl_options={'REGISTER','UNDO'}
    kind: EnumProperty(items=[(k,n,'') for k,n in TRACKS])
    start_frame: IntProperty(default=1)
    end_frame: IntProperty(default=1)
    use_playhead: BoolProperty(default=False)
    use_range: BoolProperty(default=False)

    def execute(self,context):
        s=context.scene.kimodo_studio
        try:
            if s.editing_index>=0:
                raise ValueError('Apply or cancel the current pose edit first')
            a,b=self.start_frame,self.end_frame
            kind=self.kind
            if self.use_playhead:
                a=b=context.scene.frame_current; kind=s.constraint_kind
            elif self.use_range:
                a,b=s.capture_start,s.capture_end; kind=s.constraint_kind
            if len(s.constraints)>=512:
                raise ValueError('Maximum 512 constraints')
            if kind=='root2d' and s.cursor_waypoint:
                v=C.T @ np.asarray(context.scene.cursor.location)
                rec={'type':kind,'name':'Root waypoint','start_frame':a,'end_frame':b,
                     'payload':{'smooth_root_2d':[v[[0,2]].tolist()]}}
            else:
                rec=sampled_record(context,kind,a,b)
            item=put_record(s,rec)
            if kind=='root2d' and s.cursor_waypoint:
                target=bpy.data.objects.new('Kimodo Root Waypoint',None)
                context.scene.collection.objects.link(target)
                target.empty_display_type='ARROWS'; target.empty_display_size=.18
                target.location=(context.scene.cursor.location.x,context.scene.cursor.location.y,0.)
                target['kimodo_waypoint']=True; item.target=target
            ui.redraw()
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


class KMD_OT_Constraint(bpy.types.Operator):
    bl_idname='kimodo.constraint_action'
    bl_label='Constraint action'
    bl_options={'REGISTER','UNDO'}
    action: EnumProperty(items=[(x,x.title(),'') for x in ('DELETE','DUPLICATE','GOTO','RECAPTURE','EDIT','APPLY','CANCEL')])

    def execute(self,context):
        s=context.scene.kimodo_studio
        try:
            if self.action=='CANCEL':
                cleanup_editor(context); return {'FINISHED'}
            if self.action=='APPLY':
                if s.editing_index<0 or not s.edit_object:
                    raise ValueError('No constraint pose is being edited')
                obj=s.edit_object
                if context.mode!='OBJECT':
                    bpy.ops.object.mode_set(mode='OBJECT')
                with tempfile.TemporaryDirectory() as tmp:
                    clip=rig.snapshot(obj,context.scene,context.scene.frame_current,
                                      context.scene.frame_current+1,Path(tmp)/'pose.npz')
                item=s.constraints[s.editing_index]
                p=json.loads(item.payload)
                p.update(local_rot_mats=clip.local[:1].tolist(),root_positions=clip.root[:1].tolist())
                item.payload=json.dumps(p); item.translation=(0,0,0)
                cleanup_editor(context); return {'FINISHED'}
            if s.editing_index>=0:
                raise ValueError('Apply or cancel the current edit first')
            if not s.constraints:
                raise ValueError('Select a constraint')
            i=max(0,min(s.constraint_index,len(s.constraints)-1)); item=s.constraints[i]
            if self.action=='DELETE':
                # User waypoint objects are retained; no hidden scene-object deletion.
                s.constraints.remove(i); s.constraint_index=max(0,i-1)
            elif self.action=='DUPLICATE':
                r=constraint_records(s)[i]; r['enabled']=False
                put_record(s,r)  # Muted duplicate avoids immediate same-track conflicts.
            elif self.action=='GOTO':
                context.scene.frame_set(item.start_frame)
                if item.target:
                    select_only(context,item.target)
            elif self.action=='RECAPTURE':
                r=sampled_record(context,item.kind,item.start_frame,item.end_frame)
                item.payload=json.dumps(r['payload']); item.skeleton=json.dumps(r['skeleton'])
            elif self.action=='EDIT':
                if item.kind=='root2d':
                    if item.target:
                        select_only(context,item.target)
                        return {'FINISHED'}
                    raise ValueError('For a root interval, adjust its offset or edit the source curve and recapture')
                r=constraint_records(s)[i]; meta=r.get('skeleton')
                if not meta:
                    meta=json.loads(source_object(context)['kimodo_skeleton_json'])
                local=np.asarray(r['payload']['local_rot_mats'][:1]); root=np.asarray(r['payload']['root_positions'][:1])
                local=np.repeat(local,2,axis=0); root=np.repeat(root,2,axis=0)
                root += C.T @ np.asarray(r.get('translation',[0,0,0]))
                if local.shape[1]!=len(meta['names']):
                    raise ValueError('Constraint pose and source skeleton differ')
                clip=Clip(local,root,rig.scene_fps(context.scene)).validate()
                context.scene.frame_set(item.start_frame)
                if context.mode!='OBJECT':
                    bpy.ops.object.mode_set(mode='OBJECT')
                with tempfile.TemporaryDirectory() as tmp:
                    path=Path(tmp)/'editor.npz'
                    save_portable(path,clip,meta,forward_native(local,root,meta))
                    for _,_,obj in rig.bake_motion(path,context.scene,item.start_frame,'Kimodo Constraint Edit'):
                        pass
                action=obj.animation_data.action
                obj.animation_data_clear(); action.use_fake_user=False
                if action.users==0:
                    bpy.data.actions.remove(action)
                obj['kimodo_constraint_editor']=True
                s.edit_object=obj; s.editing_index=i
                select_only(context,obj); bpy.ops.object.mode_set(mode='POSE')
            ui.redraw()
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


class KMD_OT_CurvePath(bpy.types.Operator):
    bl_idname='kimodo.curve_constraint'
    bl_label='Selected curve to 2D root path'
    bl_options={'REGISTER','UNDO'}

    def execute(self,context):
        try:
            obj=context.object; s=context.scene.kimodo_studio
            if not obj or obj.type!='CURVE' or len(obj.data.splines)!=1:
                raise ValueError('Select a curve with one POLY or Bezier spline')
            spline=obj.data.splines[0]; points=[]
            if spline.type=='POLY':
                points=[obj.matrix_world @ p.co.to_3d() for p in spline.points]
                if spline.use_cyclic_u and points:
                    points.append(points[0])
            elif spline.type=='BEZIER':
                from mathutils.geometry import interpolate_bezier
                ps=spline.bezier_points; count=len(ps) if spline.use_cyclic_u else len(ps)-1
                for i in range(count):
                    a,b=ps[i],ps[(i+1)%len(ps)]
                    samples=interpolate_bezier(a.co,a.handle_right,b.handle_left,b.co,max(3,spline.resolution_u+1))
                    points.extend(obj.matrix_world @ p for p in (samples if not points else samples[1:]))
            else:
                raise ValueError('Convert NURBS to a POLY or Bezier curve first')
            xy=np.asarray([[p.x,-p.y] for p in points])
            if len(xy)<2:
                raise ValueError('Path needs two or more points')
            distance=np.r_[0.,np.cumsum(np.linalg.norm(np.diff(xy,axis=0),axis=-1))]
            keep=np.r_[True,np.diff(distance)>1e-8]; xy,distance=xy[keep],distance[keep]
            n=s.capture_end-s.capture_start+1
            if len(xy)<2 or not 2<=n<=1200:
                raise ValueError('Use a non-zero-length path and a 2–1200-frame interval')
            t=np.linspace(0,distance[-1],n)
            path=np.stack([np.interp(t,distance,xy[:,axis]) for axis in range(2)],axis=-1)
            put_record(s,{'name':obj.name,'type':'root2d','start_frame':s.capture_start,'end_frame':s.capture_end,
                          'payload':{'smooth_root_2d':path.tolist()}})
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


class KMD_OT_ImportConstraints(bpy.types.Operator,ImportHelper):
    bl_idname='kimodo.import_constraints'; bl_label='Import native constraints JSON'
    bl_options={'REGISTER','UNDO'}
    filename_ext='.json'; filter_glob:StringProperty(default='*.json',options={'HIDDEN'})
    append: BoolProperty(name='Append instead of replace',default=False)
    def execute(self,context):
        s=context.scene.kimodo_studio
        try:
            if s.editing_index>=0:
                raise ValueError('Apply or cancel the pose edit first')
            records=native_to_records(load_authoring_json(self.filepath),s.constraint_import_fps,
                                      rig.scene_fps(context.scene),ui.timeline_origin(s))
            if len(records)+(len(s.constraints) if self.append else 0)>512:
                raise ValueError('Too many constraints')
            if not self.append:
                s.constraints.clear()
            for r in records:
                put_record(s,r)
        except Exception as exc:
            self.report({'ERROR'},str(exc)); return {'CANCELLED'}
        return {'FINISHED'}


